import { Router } from 'express';
import { setInventoryHandler, adjustInventoryHandler, getMyInventoryHandler, searchStockHandler, createRequestHandler, getMyRequestsHandler, listRequestsHandler, getRequestByIdHandler, claimRequestHandler, updateDispatchStatusHandler, commitDonorHandler, releaseDonorHandler, completeDonorDonationHandler, getActiveAlertsHandler, cancelRequestHandler, } from '../controllers/bloodController';
import { authenticate, authorizeRoles } from '../middlewares/authMiddleware';
const router = Router();
router.get('/inventory/search', searchStockHandler);
router.get('/inventory/me', authenticate, authorizeRoles('HOSPITAL'), getMyInventoryHandler);
router.put('/inventory', authenticate, authorizeRoles('HOSPITAL'), setInventoryHandler);
router.patch('/inventory/adjust', authenticate, authorizeRoles('HOSPITAL'), adjustInventoryHandler);
router.post('/requests', authenticate, createRequestHandler);
router.post('/request', authenticate, createRequestHandler);
router.get('/requests/mine', authenticate, getMyRequestsHandler);
router.get('/requests/alerts', authenticate, getActiveAlertsHandler);
router.get('/alerts', authenticate, getActiveAlertsHandler);
router.get('/requests', authenticate, authorizeRoles('HOSPITAL', 'ADMIN'), listRequestsHandler);
router.get('/requests/:id', authenticate, getRequestByIdHandler);
router.post('/requests/:id/claim', authenticate, authorizeRoles('HOSPITAL'), claimRequestHandler);
router.post('/requests/:id/commit-donor', authenticate, commitDonorHandler);
router.post('/requests/:id/release-donor', authenticate, releaseDonorHandler);
router.post('/requests/:id/complete-donor', authenticate, authorizeRoles('HOSPITAL'), completeDonorDonationHandler);
router.patch('/requests/:id/status', authenticate, authorizeRoles('HOSPITAL'), updateDispatchStatusHandler);
router.post('/requests/:id/cancel', authenticate, cancelRequestHandler);
export default router;
